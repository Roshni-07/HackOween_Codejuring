"""
sim/meshes.py — tiny procedural mesh builder for visual-only set dressing.

Halloween decorations (wall panels, trims, spider webs, bat silhouettes, the
jack-o'-lantern decal) are flat geometry. Instead of spawning hundreds of
primitive bodies, each decoration *layer* is accumulated into one triangle
mesh, written as a Wavefront OBJ and loaded with a single
``createVisualShape(GEOM_MESH)`` + ``createMultiBody(baseMass=0,
baseCollisionShapeIndex=-1)`` call.

Why this design:
  * Visual-only bodies have NO collision shape, so they never affect physics,
    raycasts (/depth) or the collision checks in the driver.
  * One body per layer keeps the TinyRenderer frame cost low.
  * No multi-link ``createMultiBody`` link arrays are used anywhere (those
    were the source of the earlier C-API crashes).

Every triangle is emitted double-sided: a front copy plus a reversed copy
pushed back 0.5 mm along the normal. That makes the decals render correctly
whether or not a renderer back-face culls, without z-fighting.
"""

import hashlib
import math
import os
import tempfile

import pybullet as p

ASSET_DIR = os.path.join(tempfile.gettempdir(), "hackoween_sim_assets")
_BACKFACE_OFFSET = 0.0005


def _sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def _add(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def _scale(a, s):
    return (a[0] * s, a[1] * s, a[2] * s)


def _cross(a, b):
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def _norm(a):
    length = math.sqrt(a[0] ** 2 + a[1] ** 2 + a[2] ** 2)
    if length < 1e-12:
        return (0.0, 0.0, 1.0)
    return (a[0] / length, a[1] / length, a[2] / length)


class Mesh:
    """Accumulates flat triangles and serialises them to OBJ."""

    def __init__(self, name):
        self.name = name
        self.vertices = []
        self.normals = []
        self.faces = []  # (v1, v2, v3, normal_index) — zero-based

    # -- primitives ---------------------------------------------------------
    def add_triangle(self, a, b, c, normal_hint=None, double_sided=True):
        n = _norm(_cross(_sub(b, a), _sub(c, a)))
        if normal_hint is not None:
            # Flip winding so the face normal agrees with the hint.
            if n[0] * normal_hint[0] + n[1] * normal_hint[1] + n[2] * normal_hint[2] < 0:
                b, c = c, b
                n = _scale(n, -1.0)
        self._emit(a, b, c, n)
        if double_sided:
            off = _scale(n, -_BACKFACE_OFFSET)
            self._emit(_add(a, off), _add(c, off), _add(b, off), _scale(n, -1.0))

    def add_quad(self, a, b, c, d, normal_hint=None):
        self.add_triangle(a, b, c, normal_hint)
        self.add_triangle(a, c, d, normal_hint)

    def add_fan(self, centre, ring, normal_hint):
        """Closed polygon triangulated as a fan from an interior point."""
        for i in range(len(ring)):
            self.add_triangle(centre, ring[i], ring[(i + 1) % len(ring)], normal_hint)

    def add_segment(self, a, b, width, plane_normal):
        """A thread/line of given width lying in the plane with plane_normal."""
        direction = _sub(b, a)
        side = _scale(_norm(_cross(plane_normal, direction)), width / 2.0)
        self.add_quad(_sub(a, side), _sub(b, side), _add(b, side), _add(a, side), plane_normal)

    def add_polyline(self, points, width, plane_normal, closed=False):
        count = len(points) if closed else len(points) - 1
        for i in range(count):
            self.add_segment(points[i], points[(i + 1) % len(points)], width, plane_normal)

    def _emit(self, a, b, c, n):
        base = len(self.vertices)
        self.vertices.extend([a, b, c])
        self.normals.append(n)
        self.faces.append((base, base + 1, base + 2, len(self.normals) - 1))

    # -- output -------------------------------------------------------------
    def to_obj(self):
        lines = ["# generated by sim/meshes.py — %s" % self.name, "o %s" % self.name]
        lines += ["v %.5f %.5f %.5f" % v for v in self.vertices]
        lines += ["vn %.5f %.5f %.5f" % n for n in self.normals]
        lines.append("vt 0.5 0.5")
        for a, b, c, n in self.faces:
            lines.append("f %d/1/%d %d/1/%d %d/1/%d" % (a + 1, n + 1, b + 1, n + 1, c + 1, n + 1))
        return "\n".join(lines) + "\n"

    def write(self, directory=ASSET_DIR):
        """Writes the OBJ (content-hashed filename, so caches never go stale)."""
        text = self.to_obj()
        digest = hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]
        os.makedirs(directory, exist_ok=True)
        path = os.path.join(directory, "%s_%s.obj" % (self.name, digest))
        if not os.path.exists(path):
            tmp = path + ".tmp"
            with open(tmp, "w", encoding="utf-8") as fh:
                fh.write(text)
            os.replace(tmp, path)
        return path


def spawn_visual_mesh(mesh, rgba):
    """Loads a Mesh as a static, collision-free visual body. Returns body id."""
    if not mesh.faces:
        return None
    path = mesh.write()
    vis = p.createVisualShape(p.GEOM_MESH, fileName=path, meshScale=[1, 1, 1], rgbaColor=list(rgba))
    return p.createMultiBody(
        baseMass=0,
        baseCollisionShapeIndex=-1,
        baseVisualShapeIndex=vis,
        basePosition=[0, 0, 0],
    )
